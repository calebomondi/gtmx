// Writes src/components/world-grid.ts: the world's land as a 5° grid, for the
// rotating globe. Run from waitlist/: `bun scripts/make-world-grid.mjs`.
//
// Source: Natural Earth 110m land (public domain), via the world-atlas package.
// A cell is land when any of five points in it is (its centre and four inner
// corners), so small islands such as Japan or the UK still show. The poles are
// left out: Antarctica below 60°S would only weigh the globe's bottom, and the
// Arctic above 70°N piles into thin stripes on a globe tilted towards you.
import { writeFileSync } from 'node:fs'
import { geoContains } from 'd3-geo'
import { feature } from 'topojson-client'
import world from 'world-atlas/land-110m.json' with { type: 'json' }

const STEP = 5
const SOUTH_LIMIT = -60
const NORTH_LIMIT = 70
const land = feature(world, world.objects.land)

const rows = []
for (let lat = 90 - STEP / 2; lat > -90; lat -= STEP) {
  let row = ''
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) {
    const q = STEP / 4
    const points = [[lon, lat], [lon - q, lat - q], [lon - q, lat + q], [lon + q, lat - q], [lon + q, lat + q]]
    row += lat > SOUTH_LIMIT && lat < NORTH_LIMIT && points.some((p) => geoContains(land, p)) ? '#' : '.'
  }
  rows.push(row)
}

const out = `// Generated by scripts/make-world-grid.mjs from Natural Earth 110m land
// (public domain). Do not edit by hand: rerun the script.

/** Degrees per cell. */
export const CELL_DEGREES = ${STEP}

/** Rows from north to south, columns from 180°W eastwards; "#" is land. */
export const WORLD_GRID = [
${rows.map((r) => `  '${r}',`).join('\n')}
]
`
writeFileSync(new URL('../src/components/world-grid.ts', import.meta.url), out)
console.log(`world-grid.ts: ${rows.length} rows × ${rows[0].length} columns, ${rows.join('').split('#').length - 1} land cells`)
